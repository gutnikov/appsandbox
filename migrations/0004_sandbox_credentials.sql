-- Реквизиты и постоянные секреты сэндбокса.
--
-- Живут у платформы, а не в контейнере: сэндбокс останавливается при простое,
-- и всё, что он сгенерировал бы у себя, менялось бы при каждом пробуждении.
-- Для ключа подписи сессий это означало бы, что всех вошедших выбрасывает.
alter table sandboxes
  add column db_name        text,
  add column db_user        text,
  add column db_password    text,
  -- Ключ подписи сессий приложения сэндбокса. Наружу не отдаётся никогда.
  add column session_secret text;
